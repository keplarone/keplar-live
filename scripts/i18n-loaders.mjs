#!/usr/bin/env node
/**
 * Writes src/lib/i18n/loaders/<namespace>.ts: one lazy import per locale catalog that exists on disk, so each locale's strings
 * are their own chunk (server and client load only the active locale). Run after adding or removing a catalog file:
 *   node scripts/i18n-loaders.mjs
 */
import { readdirSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..", "src", "lib", "i18n");
const have = {};
for (const ns of ["common", "client", "marketing", "app"]) {
  const dir = join(root, "messages", ns);
  const codes = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(".ts") && f !== "en.ts").map((f) => f.slice(0, -3)).sort() : [];
  const Type = { common: "CommonCatalog", client: "ClientCatalog", marketing: "MarketingCatalog", app: "AppCatalog" }[ns];
  const lines = codes.map((c) => `  ${JSON.stringify(c)}: () => import("../messages/${ns}/${c}"),`);
  const body = `// Generated by scripts/i18n-loaders.mjs. Do not edit by hand.
import type { ${Type} } from "../types";

export const loaders: Record<string, () => Promise<{ default: ${Type} }>> = {
${lines.join("\n")}
};
`;
  writeFileSync(join(root, "loaders", `${ns}.ts`), body);
  have[ns] = codes;
  console.log(`${ns}: ${codes.length} catalogs`);
}

// Which locales have which catalogs. locales.ts uses it so a locale goes live (route, picker, hreflang, sitemap) only once
// its strings exist: stable locales need common + client + marketing, beta locales need common.
writeFileSync(
  join(root, "loaders", "available.ts"),
  `// Generated by scripts/i18n-loaders.mjs. Do not edit by hand.\nexport const CATALOGS: Record<string, readonly string[]> = ${JSON.stringify(have, null, 2)};\n`,
);
