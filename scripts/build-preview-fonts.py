"""
Dev tool: self-hosted preview fonts for the Create studio's look tiles and design picker.

The picker shows each typography pairing in its real typeface. Loading 16 Google Fonts stylesheets (full families, every axis)
just to draw a few words was slow and needed a third-party origin, so this script cuts one small static instance per family
(Latin only, one weight) from the OFL source files and writes public/fonts/previews/*.woff2 plus previews.css with
@font-face rules under the families' own names (so the stacks in lib/app-builder/design/presets.ts pick them up). Faces are
only downloaded when text actually uses them. Families without a local source fall back to Google Fonts on /app pages.

  python3 scripts/build-preview-fonts.py [/path/to/google-fonts-root]
"""
import os, sys, io
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools import subset

ROOT = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/sand-box/google"
OUT = os.path.join(os.path.dirname(__file__), "..", "public", "fonts", "previews")
# family -> (directory, file, weight, extra axis pins)
FACES = [
    ("Fraunces", "Fraunces", "Fraunces-VariableFont_SOFT,WONK,opsz,wght.ttf", 600, {"opsz": 72, "SOFT": 0, "WONK": 0}),
    ("Hanken Grotesk", "Hanken Grotesk", "HankenGrotesk-VariableFont_wght.ttf", 400, {}),
    ("Archivo Black", "Archivo Black", "ArchivoBlack-Regular.ttf", 400, {}),
    ("Space Grotesk", "Space Grotesk", "SpaceGrotesk-VariableFont_wght.ttf", 500, {}),
    ("Bricolage Grotesque", "Bricolage Grotesque", "BricolageGrotesque-VariableFont_opsz,wdth,wght.ttf", 700, {"opsz": 48, "wdth": 100}),
    ("Nunito", "Nunito", "Nunito-VariableFont_wght.ttf", 500, {}),
    ("Bodoni Moda", "Bodoni Moda", "BodoniModa-VariableFont_opsz,wght.ttf", 500, {"opsz": 48}),
    ("Jost", "Jost", "Jost-VariableFont_wght.ttf", 400, {}),
    ("Geist", "Geist", "Geist-VariableFont_wght.ttf", 500, {}),
    ("Gloock", "Gloock", "Gloock-Regular.ttf", 400, {}),
    ("DM Sans", "DM Sans", "DMSans-VariableFont_opsz,wght.ttf", 400, {"opsz": 14}),
    ("Manrope", "Manrope", "Manrope-VariableFont_wght.ttf", 600, {}),
    ("Unbounded", "Unbounded", "Unbounded-VariableFont_wght.ttf", 600, {}),
    ("Inter Tight", "Inter Tight", "InterTight-VariableFont_wght.ttf", 400, {}),
    ("Figtree", "Figtree", "Figtree-VariableFont_wght.ttf", 400, {}),
    ("JetBrains Mono", "JetBrains Mono", "JetBrainsMono-VariableFont_wght.ttf", 500, {}),
    ("Syne", "Syne", "Syne-VariableFont_wght.ttf", 700, {}),
    ("Instrument Serif", "Instrument Serif", "InstrumentSerif-Regular.ttf", 400, {}),
    ("Instrument Sans", "Instrument Sans", "InstrumentSans-VariableFont_wdth,wght.ttf", 400, {"wdth": 100}),
    ("Dela Gothic One", "Dela Gothic One", "DelaGothicOne-Regular.ttf", 400, {}),
    ("Karla", "Karla", "Karla-VariableFont_wght.ttf", 400, {}),
    ("Playfair Display", "Playfair Display", "PlayfairDisplay-VariableFont_wght.ttf", 600, {}),
    ("Sora", "Sora", "Sora-VariableFont_wght.ttf", 400, {}),
    ("IBM Plex Sans", "IBM Plex Sans", "IBMPlexSans-VariableFont_wdth,wght.ttf", 400, {"wdth": 100}),
]
UNICODES = "U+0020-007E,U+00A0-00FF,U+2013-2014,U+2018-201D,U+2022,U+2026,U+2192"

def main():
    os.makedirs(OUT, exist_ok=True)
    css = ["/* Generated by scripts/build-preview-fonts.py: Latin preview cuts of OFL Google Fonts for the Create studio. Do not edit. */"]
    total = 0
    for family, d, f, weight, pins in FACES:
        src = os.path.join(ROOT, d, f)
        if not os.path.exists(src):
            print("skip (no source)", family)
            continue
        font = TTFont(src)
        if "fvar" in font:
            axes = {a.axisTag: a for a in font["fvar"].axes}
            loc = {}
            for tag, a in axes.items():
                v = weight if tag == "wght" else pins.get(tag, a.defaultValue)
                loc[tag] = max(a.minValue, min(a.maxValue, v))
            font = instancer.instantiateVariableFont(font, loc)
        opts = subset.Options()
        opts.flavor = "woff2"
        opts.layout_features = ["kern", "liga", "calt"]
        opts.name_IDs = [1, 2]
        opts.notdef_outline = True
        sub = subset.Subsetter(opts)
        sub.populate(unicodes=subset.parse_unicodes(UNICODES))
        sub.subset(font)
        slug = family.lower().replace(" ", "-")
        out = os.path.join(OUT, f"{slug}.woff2")
        font.flavor = "woff2"
        font.save(out)
        size = os.path.getsize(out)
        total += size
        css.append(f'@font-face{{font-family:"{family}";src:url("/fonts/previews/{slug}.woff2") format("woff2");font-weight:100 900;font-style:normal;font-display:swap;unicode-range:{UNICODES}}}')
        print(f"{family}: {size // 1024} KB")
    with open(os.path.join(OUT, "previews.css"), "w") as fh:
        fh.write("\n".join(css) + "\n")
    print(f"total {total // 1024} KB")

main()
